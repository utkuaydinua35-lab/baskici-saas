def _normalize_to_spec_key(model: str) -> str:
    """Telefon model adını MODEL_SPECS anahtar formatına çevir.
    'iPhone 15 Pro Max' -> 'IPHONE-15-PROMAX', 'Galaxy A23' -> 'SAMSUNG-A23' vb.
    """
    if not model:
        return ""
    s = model.upper().strip()
    # Türkçe karakterleri sadeleştir
    for a, b in [("Ş", "S"), ("Ç", "C"), ("Ö", "O"), ("Ü", "U"), ("Ğ", "G"), ("İ", "I"), ("I", "I")]:
        s = s.replace(a, b)
    # Marka normalizasyonu
    s = s.replace("GALAXY", "SAMSUNG").replace("APPLE", "")
    s = re.sub(r"I\s*PHONE", "IPHONE", s)
    # Samsung S/A/M serisi 'SAMSUNG-' önekiyle saklanıyor ama S/A doğrudan da olabilir
    s = s.replace("IPHONE", "IPHONE ")
    s = re.sub(r"\s+", " ", s).strip()
    s = s.replace(" ", "-").replace("--", "-")
    s = s.replace("PRO-MAX", "PROMAX")
    return s.strip("-")


def get_spec(model: str):
    """Model için (width_cm, height_cm, radius_cm) döndür; bulunamazsa None.
    Sadece sunucu-içi render için. Asla API'den dönülmez.
    """
    if not model:
        return None
    key = _normalize_to_spec_key(model)
    if key in _MODEL_SPECS:
        return _MODEL_SPECS[key]
    # Samsung kısa anahtar denemeleri (S23-ULTRA gibi doğrudan)
    for prefix in ("", "SAMSUNG-"):
        alt = prefix + key.replace("SAMSUNG-", "")
        if alt in _MODEL_SPECS:
            return _MODEL_SPECS[alt]
    return None


def has_spec(model: str) -> bool:
    return get_spec(model) is not None


def spec_count() -> int:
    return len(_MODEL_SPECS)


def all_model_keys() -> list[str]:
    """Baseline model anahtarlarinin listesi (olcu doNDURMEZ — sadece adlar)."""
    return sorted(_MODEL_SPECS.keys())
